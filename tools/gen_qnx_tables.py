"""Generate tracestudio/qnx_tables.py (kernel call numbers, thread states,
message types) from the QNX SDP headers. Run once per SDP release:
    python3 tools/gen_qnx_tables.py $QNX_TARGET/usr/include > tracestudio/qnx_tables.py
"""
import re
import sys

inc = sys.argv[1]


def read(name):
    with open(f"{inc}/sys/{name}") as f:
        return re.sub(r"/\*.*?\*/|//[^\n]*", "", f.read(), flags=re.S)


ker = {}
for m in re.finditer(r"^#define\s+__KER_([A-Z0-9_]+)\s+(\d+)", read("kercalls.h"), re.M):
    ker[int(m.group(2))] = m.group(1)
states = {}
for m in re.finditer(r"^#define\s+STATE_([A-Z0-9_]+)\s+(\d+)u", read("states.h"), re.M):
    if m.group(1) not in ("MAX", "TIMEOUT_MAX"):
        states[int(m.group(2))] = m.group(1)

# C enums of the message headers: values are literals, earlier names, or name +/| literal
values, enums = {}, []
for hdr in ("sysmsg.h", "procmsg.h", "memmsg.h", "pathmsg.h", "iomsg.h"):
    for body in re.findall(r"\benum\b[^{;]*\{(.*?)\}", read(hdr), re.S):
        entries, nxt = [], 0
        for item in body.split(","):
            item = item.strip()
            if not item:
                continue
            m = re.match(r"^([A-Za-z_]\w*)\s*(?:=\s*(.+))?$", item, re.S)
            if not m:
                break
            name, expr = m.group(1), m.group(2)
            if expr is not None:
                try:
                    nxt = eval(re.sub(r"\b(0x[0-9a-fA-F]+|\d+)[uUlL]*\b", r"\1", expr), {}, dict(values))
                except Exception:
                    break
            values[name] = nxt
            entries.append((name, nxt, (expr or "").strip()))
            nxt += 1
        enums.append(entries)

BASES = ("_SYSMGR_BASE", "_PROCMGR_BASE", "_MEMMGR_BASE", "_PATHMGR_BASE", "_IO_BASE")
types, connect = {}, {}
for entries in enums:
    if not entries:
        continue
    if entries[0][0] == "_IO_CONNECT_COMBINE":
        connect = {v: n for n, v, _ in entries if n != "_IO_CONNECT_LAST"}
    elif entries[0][2] in BASES:   # main type enum of a manager: first entry = <manager>_BASE
        for n, v, _ in entries:
            if not n.endswith(("_MAX", "_BASE")):
                types.setdefault(v, n)

print("# Generated by tools/gen_qnx_tables.py from the QNX SDP 8.0 headers <sys/kercalls.h>,")
print("# <sys/states.h>, <sys/sysmsg.h>, <sys/procmsg.h>, <sys/memmsg.h>, <sys/pathmsg.h> and")
print("# <sys/iomsg.h>. Do not edit.")
for title, table in (("KERCALLS", ker), ("STATES", states)):
    print(f"{title} = {{")
    for k in sorted(table):
        print(f"    {k}: {table[k]!r},")
    print("}")
print("# first 16 bits of a message: system (< 0x100, procnto) and resource-manager (0x100-0x1ff) types")
print("MSG_TYPES = {")
for k in sorted(types):
    print(f"    0x{k:03x}: {types[k]!r},")
print("}")
print("# _IO_CONNECT subtype (second 16 bits of an _IO_CONNECT message)")
print("IO_CONNECT_SUBTYPES = {")
for k in sorted(connect):
    print(f"    {k}: {connect[k]!r},")
print("}")
