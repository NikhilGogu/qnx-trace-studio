"""Generate tracestudio/qnx_tables.py (kernel call numbers, thread states)
from the QNX SDP headers. Run once per SDP release:
    python3 tools/gen_qnx_tables.py $QNX_TARGET/usr/include > tracestudio/qnx_tables.py
"""
import re
import sys

inc = sys.argv[1]
ker = {}
for m in re.finditer(r"^#define\s+__KER_([A-Z0-9_]+)\s+(\d+)", open(f"{inc}/sys/kercalls.h").read(), re.M):
    ker[int(m.group(2))] = m.group(1)
states = {}
for m in re.finditer(r"^#define\s+STATE_([A-Z0-9_]+)\s+(\d+)u", open(f"{inc}/sys/states.h").read(), re.M):
    if m.group(1) not in ("MAX", "TIMEOUT_MAX"):
        states[int(m.group(2))] = m.group(1)
print("# Generated by tools/gen_qnx_tables.py from the QNX SDP 8.0 headers")
print("# <sys/kercalls.h> and <sys/states.h>. Do not edit.")
print("KERCALLS = {")
for k in sorted(ker):
    print(f"    {k}: {ker[k]!r},")
print("}")
print("STATES = {")
for k in sorted(states):
    print(f"    {k}: {states[k]!r},")
print("}")
